const STORAGE_KEY = "mortigenLandingLang";
const SUPPORTED_LANGS = ["en","es","zh","fr","hi","pt","ru","eu","de","it","ja","bn","ko"];

function pageSupportedLanguages() {
  const pageLanguages = [...document.querySelectorAll("[data-lang-toggle]")]
    .map((button) => button.dataset.langToggle)
    .filter((lang) => SUPPORTED_LANGS.includes(lang));

  return pageLanguages.length > 0 ? pageLanguages : SUPPORTED_LANGS;
}

function translatePage(lang) {
  const copy = {
    ...(HOME_TRANSLATIONS.en || {}),
    ...(LEGAL_TRANSLATIONS.en || {}),
    ...(LANDING_TRANSLATIONS.en || {}),
    ...(HOME_TRANSLATIONS[lang] || {}),
    ...(LEGAL_TRANSLATIONS[lang] || {}),
    ...(LANDING_TRANSLATIONS[lang] || {})
  };

  const hasCopy = (key) => Object.prototype.hasOwnProperty.call(copy, key);

  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (hasCopy(key)) {
      element.textContent = copy[key];
    }
  });

  const titleElement = document.querySelector("title[data-i18n]");
  if (titleElement) {
    document.title = titleElement.textContent;
  }

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.dataset.i18nHtml;
    if (hasCopy(key)) {
      element.innerHTML = copy[key];
    }
  });

  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    const key = element.dataset.i18nContent;
    if (hasCopy(key)) {
      element.setAttribute("content", copy[key]);
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (hasCopy(key)) {
      element.setAttribute("alt", copy[key]);
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (hasCopy(key)) {
      element.setAttribute("aria-label", copy[key]);
    }
  });

  document.querySelectorAll("[data-i18n-href]").forEach((element) => {
    const key = element.dataset.i18nHref;
    if (hasCopy(key)) {
      element.setAttribute("href", copy[key]);
    }
  });

  document.querySelectorAll("[data-i18n-src]").forEach((element) => {
    const key = element.dataset.i18nSrc;
    if (hasCopy(key)) {
      element.setAttribute("src", copy[key]);
    }
  });

  document.querySelectorAll("[data-lang-toggle]").forEach((button) => {
    button.setAttribute(
      "aria-pressed",
      String(button.dataset.langToggle === lang)
    );
  });

  document.querySelectorAll("[data-lang-trigger-label]").forEach((label) => {
    const activeButton = document.querySelector(
      `[data-lang-toggle="${lang}"]`
    );
    if (activeButton) {
      label.textContent = activeButton.textContent.trim();
    } else {
      label.textContent = lang.toUpperCase();
    }
  });
}

function persistLanguage(lang) {
  try {
    window.localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Ignore storage failures in restricted browsing contexts.
  }
}

function readStoredLanguage() {
  try {
    return window.localStorage.getItem(STORAGE_KEY);
  } catch {
    return null;
  }
}

function updateUrlLanguage(lang) {
  const url = new URL(window.location.href);
  url.searchParams.set("lang", lang);
  window.history.replaceState({}, "", `${url.pathname}${url.search}${url.hash}`);
}

function resolveInitialLanguage() {
  const pageLanguages = pageSupportedLanguages();
  const urlLanguage = new URL(window.location.href).searchParams.get("lang");
  if (pageLanguages.includes(urlLanguage)) {
    return urlLanguage;
  }

  const storedLanguage = readStoredLanguage();
  if (pageLanguages.includes(storedLanguage)) {
    return storedLanguage;
  }

  const browserLanguage = navigator.language.toLowerCase().split("-")[0];
  return pageLanguages.includes(browserLanguage) ? browserLanguage : "en";
}

function initializeLanguageSwitch() {
  const initialLanguage = resolveInitialLanguage();
  translatePage(initialLanguage);
  persistLanguage(initialLanguage);
  updateUrlLanguage(initialLanguage);

  document.querySelectorAll("[data-lang-toggle]").forEach((button) => {
    button.addEventListener("click", () => {
      const nextLanguage = button.dataset.langToggle;
      if (!pageSupportedLanguages().includes(nextLanguage)) {
        return;
      }

      translatePage(nextLanguage);
      persistLanguage(nextLanguage);
      updateUrlLanguage(nextLanguage);
    });
  });

  initializeLanguageDropdowns();
  initializeSubtleMotion();
}

function initializeSubtleMotion() {
  if (!document.querySelector(".hero") || !("IntersectionObserver" in window)) {
    return;
  }

  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
  if (reducedMotion.matches) {
    return;
  }

  const revealGroups = [
    {
      selector:
        ".hero-copy > .pill, .logo-wrap, .hero-copy > h1, .hero-actions, .hero-copy > .section-copy, .download-note",
      step: 45,
    },
    { selector: ".sprite-panel", step: 0, lift: true },
    { selector: ".proof-card", step: 45 },
    { selector: ".phone-frame", step: 60, lift: true },
    { selector: ".gameplay-cta", step: 0 },
    { selector: ".portrait-card", step: 0, lift: true },
    { selector: ".stat-card", step: 45 },
    { selector: ".section-header", step: 0 },
    { selector: ".system-card", step: 60, lift: true },
    { selector: ".feature-card", step: 55, lift: true },
    { selector: ".media-banner, .progression-media", step: 0, lift: true },
    { selector: ".threat-card, .privacy-card", step: 55, lift: true },
    { selector: ".final-download-panel, .footer-inner", step: 0 },
  ];
  const targets = [];
  const seen = new Set();

  revealGroups.forEach(({ selector, step, lift }) => {
    document.querySelectorAll(selector).forEach((element, index) => {
      if (seen.has(element)) {
        return;
      }

      seen.add(element);
      element.classList.add("motion-reveal");
      if (lift) {
        element.classList.add("motion-reveal--lift");
      }
      if (step > 0) {
        element.style.setProperty(
          "--motion-delay",
          `${Math.min(index * step, 180)}ms`
        );
      }
      targets.push(element);
    });
  });

  if (targets.length === 0) {
    return;
  }

  document.documentElement.classList.add("motion-ready");

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) {
          return;
      }

      entry.target.classList.add("is-visible");
      animateStatValue(entry.target);
      observer.unobserve(entry.target);
    });
  },
    {
      rootMargin: "0px 0px -12% 0px",
      threshold: 0.08,
    }
  );

  targets.forEach((element) => observer.observe(element));
}

function animateStatValue(element) {
  if (!element.classList.contains("stat-card") || element.dataset.statAnimated) {
    return;
  }

  const value = element.querySelector("strong");
  if (!value) {
    return;
  }

  const target = Number.parseInt(value.textContent, 10);
  if (!Number.isFinite(target)) {
    return;
  }

  element.dataset.statAnimated = "true";
  const durationMs = 720;
  let startedAt;

  const tick = (timestamp) => {
    startedAt ??= timestamp;
    const progress = Math.min((timestamp - startedAt) / durationMs, 1);
    const eased = 1 - Math.pow(1 - progress, 3);
    value.textContent = String(Math.max(1, Math.round(target * eased)));

    if (progress < 1) {
      window.requestAnimationFrame(tick);
    } else {
      value.textContent = String(target);
    }
  };

  value.textContent = "1";
  window.requestAnimationFrame(tick);
}

function initializeLanguageDropdowns() {
  const dropdowns = document.querySelectorAll("[data-lang-switch]");
  if (dropdowns.length === 0) {
    return;
  }

  const closeAll = (except) => {
    dropdowns.forEach((dropdown) => {
      if (dropdown === except) {
        return;
      }
      const trigger = dropdown.querySelector("[data-lang-trigger]");
      const menu = dropdown.querySelector("[data-lang-menu]");
      if (trigger) {
        trigger.setAttribute("aria-expanded", "false");
      }
      if (menu) {
        menu.hidden = true;
      }
    });
  };

  dropdowns.forEach((dropdown) => {
    const trigger = dropdown.querySelector("[data-lang-trigger]");
    const menu = dropdown.querySelector("[data-lang-menu]");
    if (!trigger || !menu) {
      return;
    }

    trigger.addEventListener("click", (event) => {
      event.stopPropagation();
      const expanded = trigger.getAttribute("aria-expanded") === "true";
      closeAll(expanded ? null : dropdown);
      trigger.setAttribute("aria-expanded", String(!expanded));
      menu.hidden = expanded;
    });

    menu.addEventListener("click", (event) => {
      const target = event.target.closest("[data-lang-toggle]");
      if (target) {
        trigger.setAttribute("aria-expanded", "false");
        menu.hidden = true;
      }
    });
  });

  document.addEventListener("click", (event) => {
    if (!event.target.closest("[data-lang-switch]")) {
      closeAll(null);
    }
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closeAll(null);
    }
  });
}

document.addEventListener("DOMContentLoaded", initializeLanguageSwitch);
